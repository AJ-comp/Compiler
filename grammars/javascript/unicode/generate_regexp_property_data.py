"""Regenerate ECMAScript 2026 RegExp property aliases from pinned Unicode 17.

Usage: python generate_regexp_property_data.py [local-directory] [--check]
The optional directory contains the two exact official Unicode input files.
No third-party packages are required. Ordinary builds use the generated C#.
"""

import argparse
from hashlib import sha256
from pathlib import Path
from urllib.request import urlopen


BASE_URL = "https://www.unicode.org/Public/17.0.0/ucd/"
SOURCES = {
    "PropertyAliases.txt": "4441f573caf952ffece1d7c892e7715bd7136dfc26f96eb6f268bf1e474715fb",
    "PropertyValueAliases.txt": "64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a",
}
SPEC_URL = "https://tc39.es/ecma262/2026/multipage/text-processing.html"
ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "src/FrontEnd/Parse.FrontEnd.Grammars.Ebnf/JavaScript/JavaScriptRegExpProperties.g.cs"

# Table 65 is a whitelist. The UCD also describes binary properties that
# ECMAScript expressly does not accept, so extracting every UCD property
# would incorrectly accept names such as Composition_Exclusion.
BINARY_PROPERTIES = set("""
ASCII_Hex_Digit Alphabetic Bidi_Control Bidi_Mirrored Case_Ignorable Cased
Changes_When_Casefolded Changes_When_Casemapped Changes_When_Lowercased
Changes_When_NFKC_Casefolded Changes_When_Titlecased Changes_When_Uppercased
Dash Default_Ignorable_Code_Point Deprecated Diacritic Emoji Emoji_Component
Emoji_Modifier Emoji_Modifier_Base Emoji_Presentation Extended_Pictographic
Extender Grapheme_Base Grapheme_Extend Hex_Digit IDS_Binary_Operator
IDS_Trinary_Operator ID_Continue ID_Start Ideographic Join_Control
Logical_Order_Exception Lowercase Math Noncharacter_Code_Point Pattern_Syntax
Pattern_White_Space Quotation_Mark Radical Regional_Indicator Sentence_Terminal
Soft_Dotted Terminal_Punctuation Unified_Ideograph Uppercase Variation_Selector
White_Space XID_Continue XID_Start
""".split())

# Table 66 names have no aliases and are only accepted in Unicode-sets mode.
STRING_PROPERTIES = """
Basic_Emoji Emoji_Keycap_Sequence RGI_Emoji_Modifier_Sequence
RGI_Emoji_Flag_Sequence RGI_Emoji_Tag_Sequence RGI_Emoji_ZWJ_Sequence RGI_Emoji
""".split()


def rows(data):
    for line in data.decode("utf-8").splitlines():
        content = line.split("#", 1)[0].strip()
        if content:
            yield [field.strip() for field in content.split(";")]


def generate(source):
    categories = set()
    scripts = set()
    binary = {"ASCII", "Any", "Assigned"}
    found = set()
    for fields in rows(source["PropertyAliases.txt"]):
        if len(fields) >= 2 and fields[1] in BINARY_PROPERTIES:
            found.add(fields[1])
            # Table 65 permits White_Space and space, but not UCD's WSpace.
            binary.update(field for field in fields if field != "WSpace")
    if found != BINARY_PROPERTIES:
        raise SystemExit("The pinned property aliases no longer match Table 65.")
    for fields in rows(source["PropertyValueAliases.txt"]):
        if fields[0] == "gc":
            categories.update(fields[1:])
        elif fields[0] == "sc":
            scripts.update(fields[1:])
    if len(categories) != 80 or len(scripts) != 346 or len(binary) != 98:
        raise SystemExit("Unexpected alias count in the pinned Unicode data.")
    lines = [
        "// <auto-generated>",
        "// ECMAScript 2026 RegExp property aliases, Unicode 17.0.0.",
        "// Allowed property names: " + SPEC_URL + "#table-binary-unicode-properties",
    ]
    for name, digest in SOURCES.items():
        lines += ["// Source: " + BASE_URL + name, "// SHA-256: " + digest]
    lines += [
        "// Unicode data copyright Unicode, Inc.; see grammars/javascript/unicode/LICENSE.txt.",
        "// Regenerate with grammars/javascript/unicode/generate_regexp_property_data.py.",
        "// </auto-generated>",
        "namespace Janglim.FrontEnd.Grammars.JavaScript",
        "{",
        "    internal static partial class JavaScriptRegExpProperties",
        "    {",
    ]
    for field, values in [("GeneralCategories", categories), ("Scripts", scripts),
                          ("BinaryProperties", binary), ("StringProperties", STRING_PROPERTIES)]:
        values = sorted(values)
        lines += ["        private static readonly string[] " + field + " =", "        {"]
        for index in range(0, len(values), 4):
            lines += ["            " + ", ".join('"' + value + '"' for value in values[index:index + 4]) + ","]
        lines += ["        };", ""]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main():
    arguments = argparse.ArgumentParser(description=__doc__)
    arguments.add_argument("directory", nargs="?", type=Path)
    arguments.add_argument("--check", action="store_true")
    options = arguments.parse_args()
    source = {}
    for name, expected_hash in SOURCES.items():
        data = (options.directory / name).read_bytes() if options.directory else urlopen(BASE_URL + name).read()
        if sha256(data).hexdigest() != expected_hash:
            raise SystemExit(name + " differs from the pinned Unicode 17.0.0 source.")
        source[name] = data
    result = generate(source)
    if options.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("The generated RegExp property table is out of date.")
        print("RegExp property table matches both pinned inputs.")
    else:
        OUTPUT.write_text(result, encoding="utf-8")
        print(OUTPUT)


if __name__ == "__main__":
    main()
