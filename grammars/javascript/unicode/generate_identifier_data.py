"""Regenerate the pinned Unicode identifier tables (Python 3, no packages).

Usage: python grammars/javascript/unicode/generate_identifier_data.py [local-file]
The optional local file must be the exact official Unicode 17.0.0 input.
"""

from hashlib import sha256
from pathlib import Path
import re
import sys
from urllib.request import urlopen

URL = "https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "src/FrontEnd/Parse.FrontEnd.Grammars.Ebnf/JavaScript/JavaScriptUnicodeData.g.cs"


def merge(ranges):
    result = []
    for start, end in sorted(ranges):
        if result and start <= result[-1][1] + 1:
            result[-1] = (result[-1][0], max(end, result[-1][1]))
        else:
            result.append((start, end))
    return result


data = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urlopen(URL).read()
if sha256(data).hexdigest() != SHA256:
    raise SystemExit("Unicode source hash differs from the pinned 17.0.0 source.")
properties = {"ID_Start": [], "ID_Continue": []}
for line in data.decode("utf-8").splitlines():
    match = re.match(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#", line)
    if match and match[3] in properties:
        properties[match[3]].append((int(match[1], 16), int(match[2] or match[1], 16)))

# ECMAScript adds '$' and '_' to ID_Start, and '$' to ID_Continue.
# Unicode 17 already includes '_' and U+200C/U+200D in ID_Continue.
properties["ID_Start"] += [(0x24, 0x24), (0x5F, 0x5F)]
properties["ID_Continue"] += [(0x24, 0x24)]
lines = [
    "// <auto-generated>",
    "// Unicode 17.0.0 ID_Start / ID_Continue, with ECMAScript additions.",
    "// Source: " + URL,
    "// SHA-256: " + SHA256,
    "// Unicode data copyright Unicode, Inc.; see grammars/javascript/unicode/LICENSE.txt.",
    "// Regenerate with grammars/javascript/unicode/generate_identifier_data.py.",
    "// </auto-generated>",
    "namespace Janglim.FrontEnd.Grammars.JavaScript",
    "{",
    "    internal static class JavaScriptUnicodeData",
    "    {",
    '        internal const string Version = "17.0.0";',
]
for property_name, field in [("ID_Start", "StartRanges"), ("ID_Continue", "PartRanges")]:
    ranges = merge(properties[property_name])
    assert len(ranges) > 600
    lines += ["", "        internal static readonly int[] " + field + " =", "        {"]
    for i in range(0, len(ranges), 4):
        lines.append("            " + ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in ranges[i:i + 4]) + ",")
    lines += ["        };"]
lines += ["    }", "}", ""]
OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(OUTPUT)
