namespace Janglim.FrontEnd.Parsers.Tests;

/// <summary>
/// Registered C# conditions travel from EBNF text to their exact zero-width parser position.
/// The reader must preserve existing groups/quantifiers and never execute grammar text as code.
/// </summary>
[Trait("Category", "Ebnf")]
public class EbnfPredicateTests
{
    [Fact]
    public void Reading_attaches_the_registered_callback_to_a_distinct_epsilon_production()
    {
        int calls = 0;
        var options = new EbnfReaderOptions().RegisterPredicate("Allow", context => { calls++; return true; });

        var grammar = Read("S : 'x' {Allow()}? 'y' | 'x' 'y' 'z' ;", options);

        Assert.Equal(0, calls); // Reading and lowering do not evaluate user code.
        var condition = Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null);
        Assert.True(condition.IsEpsilon);
        Assert.Equal("Allow", condition.Predicate.Name);
        Assert.False(condition.AutoGenerated); // Normalization must preserve the check position.

        var firstRule = grammar.StartSymbol[0];
        Assert.Equal(3, firstRule.Count);
        Assert.Equal("x", Assert.IsType<Terminal>(firstRule[0]).Value);
        Assert.Equal(condition.UniqueKey, Assert.IsType<NonTerminal>(firstRule[1]).UniqueKey);
        Assert.Equal("y", Assert.IsType<Terminal>(firstRule[2]).Value);
        Assert.Null(firstRule.Predicate);
    }

    [Fact]
    public void Consecutive_and_repeated_occurrences_keep_distinct_positions_in_source_order()
    {
        var options = new EbnfReaderOptions()
            .RegisterPredicate("First", context => true)
            .RegisterPredicate("Second", context => true);
        var grammar = Read("S : 'x' {First()}? {Second()}? {First()}? 'y' ;", options);

        var rule = grammar.StartSymbol[0];
        var conditions = rule.OfType<NonTerminal>().Select(symbol => symbol[0]).ToArray();
        Assert.Equal(new[] { "First", "Second", "First" }, conditions.Select(production => production.Predicate.Name));
        Assert.Equal(3, conditions.Select(production => production.UniqueKey).Distinct().Count());
        Assert.All(conditions, production => Assert.True(production.IsEpsilon));
        Assert.Same(conditions[0].Predicate, conditions[2].Predicate);
    }

    [Fact]
    public void Internal_predicate_names_do_not_collide_with_user_rules_or_token_rules()
    {
        var grammar = Read("""
            S : __predicate1 {Allow()}? __predicate2 {Allow()}? ;
            __predicate1 : 'x' ;
            __predicate2 := "[a-z]+" ;
            """, Allow(true));

        var guardedRules = grammar.NonTerminalSingles.Where(production => production.Predicate != null).ToArray();
        Assert.Equal(2, guardedRules.Length);
        Assert.All(guardedRules, production => Assert.DoesNotContain(production.Name, new[] { "__predicate1", "__predicate2" }));
        Assert.Equal(guardedRules.Length, guardedRules.Select(production => production.Name).Distinct().Count());
        Assert.Equal("__predicate1", Assert.IsType<NonTerminal>(grammar.StartSymbol[0][0]).Name);
    }

    [Fact]
    public void A_model_constructed_in_csharp_uses_the_same_predicate_lowering()
    {
        var model = new EbnfModel();
        var start = new EbnfRuleDef { Name = "S" };
        start.Alternatives.Add(new List<EbnfSym> { EbnfSym.Literal("x"), EbnfSym.PredicateCall("Allow") });
        model.Rules.Add(start);

        var grammar = new EbnfGrammar(model, Allow(true));

        var predicate = Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null);
        Assert.True(predicate.IsEpsilon);
        Assert.Equal("Allow", predicate.Predicate.Name);
    }

    [Fact]
    public void Model_predicates_cannot_be_made_optional_or_repeatable()
    {
        var model = new EbnfModel();
        var start = new EbnfRuleDef { Name = "S" };
        var condition = EbnfSym.PredicateCall("Allow");
        condition.Quantifier = EbnfQuantifier.Optional;
        start.Alternatives.Add(new List<EbnfSym> { condition });
        model.Rules.Add(start);

        var error = Assert.Throws<EbnfException>(() => new EbnfGrammar(model, Allow(true)));
        Assert.Contains("a predicate cannot have a quantifier", error.Message);
    }

    [Fact]
    public void Registering_an_additional_function_does_not_change_an_already_built_grammar()
    {
        var options = Allow(true);
        var grammar = Read("S : 'x' {Allow()}? ;", options);
        var existing = Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null).Predicate;

        options.RegisterPredicate("Later", context => false);

        Assert.Same(existing, Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null).Predicate);
        Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null);
        Assert.True(EbnfGrammarReader.Read("S : 'x' {Later()}? ;", options).Success);
    }

    [Theory]
    [InlineData("Allow")]
    [InlineData("allow")]
    [InlineData("_atBoundary2")]
    [InlineData("줄바꿈금지")]
    public void Simple_identifier_registration_is_supported(string name)
    {
        var options = new EbnfReaderOptions().RegisterPredicate(name, context => true);
        Assert.True(EbnfGrammarReader.Read($"S : 'x' {{{name}()}}? ;", options).Success);
    }

    [Theory]
    [InlineData("")]
    [InlineData(" ")]
    [InlineData("1Allow")]
    [InlineData("Allow()")]
    [InlineData("object.Allow")]
    [InlineData("Allow Name")]
    public void Invalid_registration_names_are_rejected_before_reading(string name)
    {
        Assert.Throws<ArgumentException>(() => new EbnfReaderOptions().RegisterPredicate(name, context => true));
    }

    [Fact]
    public void Null_registration_arguments_are_rejected()
    {
        Assert.Throws<ArgumentNullException>(() => new EbnfReaderOptions().RegisterPredicate(null, context => true));
        Assert.Throws<ArgumentNullException>(() => new EbnfReaderOptions().RegisterPredicate("Allow", null));
    }

    [Fact]
    public void Duplicate_registration_does_not_replace_the_first_function()
    {
        var options = Allow(true);
        Assert.Throws<ArgumentException>(() => options.RegisterPredicate("Allow", context => false));

        var grammar = Read("S : 'x' {Allow()}? ;", options);
        var condition = Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null);
        var token = CreateLexer(grammar).Lexing("x").TokensForParsing[0];
        Assert.True(condition.Predicate.Evaluate(new PredicateContext(null, new Janglim.FrontEnd.TokenData(grammar.GetTerminal("x"), token), 0)));
    }

    [Fact]
    public void Registered_names_are_case_sensitive()
    {
        var result = EbnfGrammarReader.Read("S : 'x' {allow()}? ;", Allow(true));
        Assert.False(result.Success);
        Assert.Contains("predicate 'allow' is not registered", Assert.Single(result.Errors));
    }

    [Fact]
    public void Missing_registration_reports_the_predicate_source_line()
    {
        var result = EbnfGrammarReader.Read("\nS : 'x'\n {Missing()}? 'y' ;");
        Assert.False(result.Success);
        Assert.Contains("line 3:", Assert.Single(result.Errors));
        Assert.Contains("predicate 'Missing' is not registered", result.Errors[0]);
    }

    [Theory]
    [InlineData("S : 'x' {Allow} ? ;", "'('")]
    [InlineData("S : 'x' {Allow(Arg)}? ;", "take no arguments")]
    [InlineData("S : 'x' {Allow()} ;", "'?' after")]
    [InlineData("S : 'x' {Allow() ;", "'}' after")]
    [InlineData("S : 'x' {()}? ;", "predicate name")]
    [InlineData("S : 'x' {Allow()}?? ;", "cannot have a quantifier")]
    [InlineData("S : 'x' {Allow()}?* ;", "cannot have a quantifier")]
    [InlineData("S : 'x' {Allow()}?+ ;", "cannot have a quantifier")]
    [InlineData("S : 'x' {return true;}? ;", "'('")]
    [InlineData("S : 'x' {Host.Allow()}? ;", "unexpected character '.'")]
    [InlineData("S : 'x' {Allow() && Other()}? ;", "unexpected character '&'")]
    public void Unsupported_expressions_report_a_reader_error(string text, string fragment)
    {
        var result = EbnfGrammarReader.Read(text, Allow(true));
        Assert.False(result.Success);
        Assert.Contains(fragment, Assert.Single(result.Errors));
        Assert.DoesNotContain("internal error:", result.Errors[0]);
    }

    [Fact]
    public void Whitespace_and_existing_comments_can_separate_predicate_syntax_tokens()
    {
        var grammar = Read("""
            S : 'x' { # the registered function follows
              Allow ( # no arguments
              ) } ? 'y' ;
            """, Allow(true));
        Assert.Equal("Allow", Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null).Predicate.Name);
    }

    [Fact]
    public void Quoted_braces_question_mark_and_regex_braces_keep_their_existing_meaning()
    {
        var grammar = Read("""
            S : '{' id '}' '?' ;
            id := "[a-z]{2,3}" ;
            """);
        Assert.DoesNotContain(grammar.NonTerminalSingles, production => production.Predicate != null);
        Assert.Equal(new[] { "?", "{", "}" }, grammar.TerminalSet.Where(terminal => terminal.TokenType == Janglim.TokenType.Operator)
            .Select(terminal => terminal.Value).OrderBy(value => value, StringComparer.Ordinal));
        Assert.Equal("[a-z]{2,3}", grammar.TerminalSet.Single(terminal => terminal.Caption == "id").Value);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void A_single_condition_accepts_or_rejects_without_consuming_a_token(bool allow)
    {
        var grammar = Read("S : 'x' {Allow()}? 'y' ;", Allow(allow));
        var result = Parse(grammar, "x y");
        Assert.Equal(allow, result.Success);
        if (allow) Assert.Equal(new[] { "x", "y" }, result.ToParseTree.AllTokens.Select(token => token.Input));
    }

    [Theory]
    [InlineData("throw value;", true)]
    [InlineData("throw\tvalue;", true)]
    [InlineData("throw /* comment */ value;", true)]
    [InlineData("throw\nvalue;", false)]
    [InlineData("throw\r\nvalue;", false)]
    [InlineData("throw/* comment\n */value;", false)]
    [InlineData("throw\u2028value;", false)]
    [InlineData("throw\u2029value;", false)]
    public void Registered_line_break_condition_uses_the_next_tokens_lexer_information(string input, bool expected)
    {
        var options = new EbnfReaderOptions().RegisterPredicate("NoLineBreak", context => !context.NextToken.HasLineBreakBefore);
        var grammar = Read("""
            S : 'throw' {NoLineBreak()}? id ';' ;
            id := "[a-z]+" ;
            comment := Comment "/\*[\s\S]*?\*/" ;
            """, options);
        Assert.Equal(expected, Parse(grammar, input).Success);
    }

    [Fact]
    public void Beginning_condition_observes_the_first_token_and_no_previous_token()
    {
        var contexts = new List<PredicateContext>();
        var options = new EbnfReaderOptions().RegisterPredicate("AtStart", context => { contexts.Add(context); return true; });
        var result = Parse(Read("S : {AtStart()}? 'x' ;", options), "x");
        Assert.True(result.Success);
        Assert.NotEmpty(contexts);
        Assert.All(contexts, context =>
        {
            Assert.Null(context.PreviousToken);
            Assert.Equal("x", context.NextToken.Input);
            Assert.Equal(0, context.TokenIndex);
            Assert.False(context.IsEndOfInput);
        });
    }

    [Fact]
    public void Ending_condition_observes_synthetic_eof_and_the_last_real_token()
    {
        var contexts = new List<PredicateContext>();
        var options = new EbnfReaderOptions().RegisterPredicate("AtEnd", context => { contexts.Add(context); return context.IsEndOfInput; });
        var result = Parse(Read("S : 'x' {AtEnd()}? ;", options), "x");
        Assert.True(result.Success);
        Assert.NotEmpty(contexts);
        Assert.All(contexts, context =>
        {
            Assert.Equal("x", context.PreviousToken.Input);
            Assert.IsType<EndMarker>(context.NextToken.Kind);
            Assert.Equal(1, context.TokenIndex);
            Assert.True(context.IsEndOfInput);
        });
    }

    [Fact]
    public void Consecutive_conditions_are_checked_in_order_at_the_same_token_boundary()
    {
        var calls = new List<string>();
        var contexts = new List<PredicateContext>();
        var options = new EbnfReaderOptions()
            .RegisterPredicate("First", context => { calls.Add("First"); contexts.Add(context); return true; })
            .RegisterPredicate("Second", context => { calls.Add("Second"); contexts.Add(context); return true; });
        var result = Parse(Read("S : 'x' {First()}? {Second()}? 'y' ;", options), "x y");
        Assert.True(result.Success);
        Assert.Equal(new[] { "First", "Second" }, calls);
        Assert.All(contexts, context =>
        {
            Assert.Equal(1, context.TokenIndex);
            Assert.Equal("x", context.PreviousToken.Input);
            Assert.Equal("y", context.NextToken.Input);
        });
    }

    [Fact]
    public void A_false_condition_stops_the_sequence_before_the_next_condition()
    {
        int laterCalls = 0;
        var options = new EbnfReaderOptions()
            .RegisterPredicate("Stop", context => false)
            .RegisterPredicate("Later", context => { laterCalls++; return true; });

        var result = Parse(Read("S : 'x' {Stop()}? {Later()}? 'y' ;", options), "x y");

        Assert.False(result.Success);
        Assert.Equal(0, laterCalls);
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void A_condition_only_rule_checks_empty_input_at_eof(bool allow)
    {
        var contexts = new List<PredicateContext>();
        var options = new EbnfReaderOptions().RegisterPredicate("Allow", context => { contexts.Add(context); return allow; });
        var result = Parse(Read("S : {Allow()}? ;", options), "");

        Assert.Equal(allow, result.Success);
        Assert.NotEmpty(contexts);
        Assert.All(contexts, context =>
        {
            Assert.Null(context.PreviousToken);
            Assert.True(context.IsEndOfInput);
            Assert.Equal(0, context.TokenIndex);
        });
    }

    [Theory]
    [InlineData("x z", "x", 1)]
    [InlineData("x y z", "y", 2)]
    public void A_condition_after_an_optional_token_keeps_its_actual_input_position(string input, string previous, int index)
    {
        var contexts = new List<PredicateContext>();
        var options = new EbnfReaderOptions().RegisterPredicate("Allow", context => { contexts.Add(context); return true; });
        var result = Parse(Read("S : 'x' 'y'? {Allow()}? 'z' ;", options), input);

        Assert.True(result.Success);
        Assert.NotEmpty(contexts);
        Assert.All(contexts, context =>
        {
            Assert.Equal(previous, context.PreviousToken.Input);
            Assert.Equal("z", context.NextToken.Input);
            Assert.Equal(index, context.TokenIndex);
        });
    }

    [Theory]
    [InlineData("x z", false, true)]
    [InlineData("x y z", true, true)]
    [InlineData("x y z", false, false)]
    public void An_optional_group_preserves_a_condition_when_present(string input, bool allow, bool expected)
    {
        var grammar = Read("S : 'x' ( {Allow()}? 'y' )? 'z' ;", Allow(allow));
        Assert.Equal(expected, Parse(grammar, input).Success);
        Assert.Single(grammar.NonTerminalSingles, production => production.Predicate != null);
    }

    [Theory]
    [InlineData("x z", true)]
    [InlineData("x x z", true)]
    [InlineData("z", false)]
    public void A_repeated_nonempty_group_preserves_each_condition_position(string input, bool expected)
    {
        var grammar = Read("S : ( 'x' {Allow()}? )+ 'z' ;", Allow(true));
        Assert.Equal(expected, Parse(grammar, input).Success);
    }

    [Fact]
    public void Predicate_free_optional_syntax_remains_optional()
    {
        var grammar = Read("S : 'x' 'y'? 'z' ;", Allow(false));
        Assert.DoesNotContain(grammar.NonTerminalSingles, production => production.Predicate != null);
        Assert.True(Parse(grammar, "x z").Success);
        Assert.True(Parse(grammar, "x y z").Success);
    }

    private static EbnfReaderOptions Allow(bool value)
        => new EbnfReaderOptions().RegisterPredicate("Allow", context => value);

    private static EbnfGrammar Read(string text, EbnfReaderOptions options = null)
    {
        var result = EbnfGrammarReader.Read(text, options);
        Assert.True(result.Success, string.Join("; ", result.Errors));
        return result.Grammar;
    }

    private static Lexer CreateLexer(EbnfGrammar grammar)
    {
        var lexer = new Lexer();
        foreach (var terminal in grammar.TerminalSet) lexer.AddTokenRule(terminal);
        return lexer;
    }

    private static ParsingResult Parse(EbnfGrammar grammar, string input)
        => new LALRParser(grammar, true).Parsing(CreateLexer(grammar).Lexing(input).TokensForParsing);
}
